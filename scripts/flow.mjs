const step = async (name, fn, check) => {
  await fn(); await page.waitForTimeout(300);
  const s = await say(); const ok = check(s);
  console.log(`${ok ? 'ok  ' : 'FAIL'} ${name}: ${s}`); if (!ok) errors.push(name);
};
